export const labelsFor = (language: Language) => projectLabels[language === "cs" ? "cs" : "en"];

// The one attention label of a project row, in words.
export function attentionText(language: Language, attention: ProjectSummary["attention"]) {
  const t = labelsFor(language);
  if (!attention) return "";
  return attention.kind === "overdue" ? t.overdue(attention.count) : t.noNextStep;
}
